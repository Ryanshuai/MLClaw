def cmd_note(a) -> None:
    """Append a dated annotation to a lead. Never edits what is already there.

    A probe records what a machine saw. This records what a PERSON found out — the
    path was mistyped, the directory turns out to be inside a container, half the
    images in that archive have no annotation. None of those are probe results and
    none of them fit in `what`, which was written before anybody looked.

    Append-only, and that is the whole design. The obvious alternative is editing
    the lead, and it destroys the thing the record is for: `lead_0006` here was
    recorded against a mistyped prefix and probed `gone`, which read as confirming
    a document's claim. Correcting the path in place would leave a record that
    looks like it was always right, and the reader six months on would have no way
    to know a conclusion had once been drawn from the wrong path. The wrong lead
    stays, annotated, and the correct path is recorded as its own lead.
    """
    project = os.path.expanduser(a.project)
    rec = read_json(leads_path(project), required=False)
    if not rec:
        broke(f"no leads file at {leads_path(project)}")
    hit = [l for l in rec["leads"] if l["lead_id"] == a.id]
    if not hit:
        refuse(f"no lead {a.id!r} in this project",
               known=[l["lead_id"] for l in rec["leads"]])
    lead = hit[0]
    lead.setdefault("notes", []).append({
        "at": now_utc(), "note": a.note,
        # What kind of amendment, because they are read differently: a `correction`
        # means an earlier conclusion is suspect, a `finding` adds to it.
        "kind": a.kind})
    if a.supersedes:
        # Stated on the lead itself rather than only in prose, so anything reading
        # the register sees that this entry has been replaced.
        lead["superseded_by"] = a.supersedes
    rec["updated_at"] = now_utc()
    atomic_write_json(leads_path(project), rec)
    emit({"lead_id": a.id, "notes": len(lead["notes"]),
          "superseded_by": lead.get("superseded_by"),
          "status": lead["status"],
          "note": "appended; nothing was overwritten"})


NOTE_KINDS = ("finding", "correction", "context")


def cmd_brief(a) -> None:
    """Render `discovery/brief.md` — the sweep as something a person reads.

    `leads.json` is the record and `report` is the table. Neither is what you hand
    somebody. A reader taking over needs three things in this order, and the order
    is the argument:

      1. what is odd            — anomalies, urgent first
      2. what to look at next   — the unswept cells of searches.md's table, ranked
      3. what was found         — last, because a findings list read first becomes
                                  an inventory, and the caveats underneath it get
                                  skipped

    Every section here is COMPUTED. That is deliberate and it is also the limit:
    the script can say two objects share a name and a byte count, that a page was
    wrong about one of four claims, that nobody has looked in git history. It
    cannot say which of those matters for this project. So the document ends with
    a section the skill fills in by hand, and it is empty until somebody does —
    an empty heading is an honest gap, and generated prose that reads like
    judgment is a lie about where the judgment came from.
    """
    project = os.path.expanduser(a.project)
    rec = read_json(leads_path(project), required=False)
    if not rec:
        refuse(f"no sweep to write up: {leads_path(project)} does not exist yet")
    leads = rec.get("leads") or []
    res, _rp = workspace_resources(project)
    link = {}
    for l in leads:
        url, derived = lead_url(l, res)
        link[l["lead_id"]] = (url, derived)

    def anchor(lead_id):
        """A lead id that jumps to its row. The blocking list names ids and the
        row carries the evidence — two screens apart in a long brief."""
        return f"[`{lead_id}`](#{lead_id})"

    cov = coverage(leads, usable_sources(project))
    anom = anomalies(leads)
    by = {s: [l for l in leads if l["status"] == s] for s in STATUSES}
    measured = [l for l in by["verified"] if l.get("bytes") is not None]
    total = sum(l["bytes"] for l in measured)

    L = [f"# Discovery brief — {os.path.basename(project)}",
         "",
         f"Swept {len(leads)} lead(s). **Not exhaustive, ever** — a sweep finds "
         f"what somebody wrote down or left a path to.",
         f"Generated from `discovery/leads.json` at {now_utc()}; regenerate with "
         f"`discover.py brief`. Do not edit above the last section.",
         ""]

    L += ["## What is odd", ""]
    if not anom:
        L += ["Nothing the detectors can see. They cover status flips, duplicate "
              "objects, verified-but-empty locations, sources a probe has already "
              "contradicted, and stale claims — **not** whether the findings make "
              "sense, which is the section at the bottom.", ""]
    else:
        for x in anom:
            tag = "**URGENT**" if x["severity"] == "urgent" else "watch"
            u = link.get(x["lead_id"], (None, False))[0]
            L += [f"- {tag} · `{x['kind']}` · {anchor(x['lead_id'])} · "
                  f"{md_link(x['path'], u)}",
                  f"  - observed: {x['observed']}",
                  f"  - means: {x['means']}"]
        L += [""]

    corrections = [(l, n) for l in leads for n in (l.get("notes") or [])
                   if n["kind"] == "correction"]
    if corrections:
        L += ["**Corrections recorded on leads** — each one means an earlier "
              "reading was drawn from the wrong thing, so anything concluded from "
              "it is suspect:", ""]
        for l, n in corrections:
            L += [f"- {anchor(l['lead_id'])} `{l['path']}` — {n['note']}"]
        L += [""]

    L += ["## What to look at next", ""]
    if cov["sources_available_but_unswept"]:
        L += ["Sources that are reachable **right now** and have produced no "
              "lead, in the order `searches.md` ranks them:", ""]
        for g in cov["sources_available_but_unswept"]:
            L += [f"{g['rank']}. **`{g['source_type']}`** — {g['why']}"]
        L += [""]
    else:
        L += ["Every reachable source has at least one lead. That is coverage, "
              "not completeness — see the grid below.", ""]
    if cov["credentials_via_worklist"]:
        L += [f"The **credentials** search has {cov['credentials_via_worklist']} "
              f"finding(s), and they are the blocking list above rather than leads "
              f"— that search is generated by the other three failing.", ""]
    if cov["subjects_with_nothing"]:
        L += [f"Subjects with nothing recorded at all: "
              f"**{', '.join(cov['subjects_with_nothing'])}**. The engine is one "
              f"sweep for four searches; a subject with no leads is a search "
              f"nobody ran.", ""]
    if cov["unclassified"]:
        L += [f"{cov['unclassified']} lead(s) carry no `--subject`, so they sit "
              f"outside the grid and outside the two checks above.", ""]

    L += ["## Who is blocking", ""]
    wl = access_worklist(leads)
    if not wl:
        L += ["Nothing is waiting on access.", ""]
    else:
        for w in wl:
            L += [f"- `{w['blocker']}` — {len(w['leads'])} lead(s): "
                  f"{', '.join(anchor(i) for i in w['leads'])}"]
        L += ["",
              "Each row is one thing to go and get. `unreachable` is **never** "
              "`gone`: none of these is evidence that anything is missing.", ""]

    L += ["## Coverage — `searches.md`'s table, as actually swept", "",
          "| source (ranked) | " + " | ".join(s for s in SUBJECTS) + " |",
          "|---|" + "---|" * len(SUBJECTS)]
    cells = {(g["source_type"], g["subject"]): g["leads"] for g in cov["grid"]}
    for src in SOURCE_RANK:
        row = [f"`{src}`"] + [str(cells.get((src, sub), "") or "·")
                              for sub in SUBJECTS]
        L += ["| " + " | ".join(row) + " |"]
    L += ["",
          "`·` is a cell with no lead. Whether that is a gap depends on the "
          "source: unreachable ones belong on the blocking list above, reachable "
          "ones in *What to look at next*.", ""]

    L += ["## What was found", "",
          f"- **verified** {len(by['verified'])} — something other than a "
          f"sentence listed it",
          f"- **gone** {len(by['gone'])} — we looked where the claim pointed and "
          f"it is not there",
          f"- **unreachable** {len(by['unreachable'])} — we could not look",
          f"- **claim** {len(by['claim'])} — a document or a person says so",
          ""]
    unsized = [l for l in leads if l.get("bytes") is None]
    if measured:
        # Every unmeasured lead counts, not only the unmeasured `verified` ones —
        # an unprobed claim is a location whose contents are not in this total
        # either. Same rule as the table, which had it right.
        L += [f"Measured {human(total)} across {len(measured)} location(s)."
              + ("" if not unsized else
                 f" {len(unsized)} location(s) were not sized, so **this total is "
                 f"a lower bound, not an inventory**."), ""]
    else:
        L += [f"**Nothing has been sized yet** — 0 of {len(leads)} location(s). "
              f"That is not a statement about how much data there is.", ""]
    for l in by["gone"]:
        u = link.get(l["lead_id"], (None, False))[0]
        ev = (f"[{l.get('evidence')}]({l['evidence_url']})"
              if l.get("evidence_url") else l.get("evidence"))
        L += [f"- **GONE** {md_link(l['path'], u)} — claimed as "
              f"{l.get('what') or '?'}; evidence was {ev}"]
    if by["gone"]:
        L += [""]
    L += ["| id | what | where | status | size | claim came from |",
          "|---|---|---|---|---|---|"]
    for l in leads:
        u, derived = link.get(l["lead_id"], (None, False))
        # A dagger on a link this script built rather than one somebody typed. A
        # guessed console route that 404s must not read like a verified location.
        mark = "†" if (u and derived) else ""
        ev = l.get("evidence") or "—"
        ev = f"[{ev}]({l['evidence_url']})" if l.get("evidence_url") else ev
        # A correction has to be visible in the row, not just in the JSON: this is
        # the column a reader scans, and `lead_0006` is the case that proves it —
        # a mistyped path that probed `gone` and read as confirming a document.
        note_bits = []
        for n in l.get("notes") or []:
            tag = "**CORRECTION**" if n["kind"] == "correction" else n["kind"]
            note_bits.append(f"{tag}: {n['note']}")
        if l.get("superseded_by"):
            note_bits.insert(0, f"**SUPERSEDED BY** {anchor(l['superseded_by'])}")
        L += [f"| <a id=\"{l['lead_id']}\"></a>`{l['lead_id']}` | "
              f"{l.get('what') or '—'} | {md_link(l['path'], u)}{mark} | "
              f"{l['status']} | "
              f"{human(l['bytes']) if l.get('bytes') is not None else '—'} | "
              f"{l.get('source_type')}: {ev} |"]
        for nb in note_bits:
            L += [f"| | ↳ {nb} | | | | |"]
    if any(link[i][0] and link[i][1] for i in link):
        L += ["",
              "† link built by this script from the path (an S3 console route, a "
              "`file://`, a W&B project). It is a convenience, not part of the "
              "finding — the path is the record, and a console that has since "
              "been reorganised gives a dead link, never a wrong status."]
    # The one section a person writes is CARRIED OVER, not regenerated. Without
    # this the file's own instruction — "do not edit above the last section" —
    # would be a trap: the next `brief` run destroys the only part that took
    # somebody's judgment, and it does it silently, having just told them where to
    # write. Regenerating has to be safe or nobody will run it twice.
    path = os.path.join(project, "discovery", BRIEF)
    kept = None
    if os.path.exists(path):
        with open(path, encoding="utf-8") as fh:
            old = fh.read()
        if READING in old:
            body = old[old.index(READING) + len(READING):].strip()
            if body and PLACEHOLDER not in body:
                kept = body

    L += ["", READING, ""]
    if kept:
        L += [kept, "",
              f"<!-- carried over by `discover.py brief`; edit freely, this "
              f"section is never regenerated -->"]
    else:
        L += [PLACEHOLDER, ""]

    os.makedirs(os.path.dirname(path), exist_ok=True)
    with open(path, "w", encoding="utf-8") as fh:
        fh.write("\n".join(L))
    emit({"project": project, "brief": path, "leads": len(leads),
          "anomalies": len(anom),
          "urgent": len([x for x in anom if x["severity"] == "urgent"]),
          "unswept_sources": [g["source_type"]
                              for g in cov["sources_available_but_unswept"]],
          "note": "computed sections only — the Reading section is written by hand"})


def save_message(rec):
    """The commit subject, built from the record so `git log` is a sweep history.

    Counts rather than prose: reading `git log -- discovery/` should show access
    arriving — 9 unreachable in July, 6 verified in August — which is the one
    trend the leads file cannot show, since it holds only the current status.
    """
    by = {}
    for l in rec.get("leads") or []:
        by[l["status"]] = by.get(l["status"], 0) + 1
    parts = ", ".join(f"{by[k]} {k}" for k in
                      ("verified", "gone", "unreachable", "claim") if by.get(k))
    n = len(rec.get("leads") or [])
    return f"discover: {n} lead(s) — {parts or 'none probed'}"


def cmd_save(a) -> None:
    """Commit the sweep's record, and only the sweep's record.

    This verb exists because writing a file and keeping it are different things,
    and the gap was invisible: `atomic_write_json` makes `leads.json` crash-safe,
    `project-init` runs `git init`, and nothing in between ever commits. So the
    file this skill calls "the thing you hand the next person instead of a
    Confluence page" sat untracked — surviving on one disk, and going nowhere on
    a clone, a push, or a `git clean`. A handover artifact that does not survive
    the handover is the failure mode this whole skill was written against, and it
    was sitting inside the skill.

    Explicit rather than automatic on every probe, because CLAUDE.md's "confirm
    before saving" outranks the convenience — and because a commit is the user's
    history, not this script's scratch space. `report` says when it is overdue.
    """
    project = os.path.expanduser(a.project)
    path = leads_path(project)
    rec = read_json(path, required=False)
    if not rec:
        refuse(f"no sweep to save: {path} does not exist yet. `record` a lead "
               f"first — there is nothing here that would be lost")
    # The brief goes with the record. It is the rendered form of the same sweep
    # and the thing a reader opens first, so committing one without the other
    # hands somebody a register with no write-up — or worse, a write-up describing
    # a sweep the repo does not contain.
    paths = [path]
    brief = os.path.join(project, "discovery", BRIEF)
    if os.path.exists(brief):
        paths.append(brief)
    # The surface reading goes with them. It is what says how much of the world the
    # register covers, so a committed leads.json beside an untracked surface.json is
    # a findings list whose scope lives on one disk — the same defect `record_unsaved`
    # warns about, one file over, and the one that makes a partial sweep read as
    # complete. A clone or a `git clean` takes it, and a handover is a clone.
    surf = surface_path(project)
    if os.path.exists(surf):
        paths.append(surf)
    report = git_save(project, paths, a.message or save_message(rec))
    emit({"project": project, "record": path, **report,
          "note": None if report["committed"] else report["why"]})
    if not report["committed"] and report["why"] and "already committed" not in report["why"]:
        # Worked, and the answer is no: nothing was preserved. Exit 1 so a caller
        # that assumed the record is now safe finds out here.
        sys.exit(1)


def cmd_report(a) -> None:
    project = os.path.expanduser(a.project)
    # A mistyped --project must NOT reach the empty-record branch below. Without
    # this line the one verb people run to ask "what do we know" answers "nothing
    # recorded yet" for a project that does not exist — a false empty, produced by
    # the tool whose entire purpose is keeping "looked, nothing there" apart from
    # "could not look". Every other verb already refuses; this one is the one a
    # reader trusts most.
    if not os.path.isdir(project):
        broke(f"project not found: {project}",
              hint="--project takes a PATH to the project directory, not a "
                   "bare name; workspace root is in CLAUDE.md -> workspace_root")
    rec = read_json(leads_path(project), required=False)
    if rec is None:
        return emit({"leads": [], "note": "nothing recorded yet — discover.py "
                                          "sources lists what there is to sweep"})
    leads = rec["leads"]
    by = {k: [l for l in leads if l["status"] == k] for k in STATUSES}
    unprobed = [l for l in leads if not l["probes"]]
    stale = [l for l in leads if l["probes"]
             and (age_days(l["probes"][-1]["at"]) or 0) >= a.recheck_days]

    def slim(l):
        p = l["probes"][-1] if l["probes"] else None
        return {"lead_id": l["lead_id"], "path": l["path"], "on": l["on"],
                "status": l["status"], "source_type": l["source_type"],
                "what": l.get("what"), "evidence": l.get("evidence"),
                "dataset": l.get("dataset"),
                # null is "not measured", never zero. Three causes and the
                # status says which: never probed, could not look, or the walk
                # ran out of budget.
                "bytes": l.get("bytes"), "files": l.get("files"),
                "size_not_measured": l.get("size_not_measured"),
                "last_probe": p and {"at": p["at"], "detail": p["detail"],
                                     "age_days": age_days(p["at"])}}

    measured = [l for l in leads if l["status"] == "verified"
                and l.get("bytes") is not None]
    # The surface reading counts as part of the record. A tracked leads.json beside
    # an untracked surface.json is a findings list whose SCOPE exists on one disk,
    # which is how a 5%-coverage sweep survives a handover reading as complete.
    unsaved = not git_tracked(project, leads_path(project)) or (
        os.path.exists(surface_path(project))
        and not git_tracked(project, surface_path(project)))
    if not a.json:
        print(table(leads, a.recheck_days, unsaved))
        return

    emit({
        "project": project,
        # Gaps BEFORE counts, deliberately. A findings list with the caveats
        # underneath it is a findings list read as an inventory — the same
        # ordering rule as a partial census banner.
        # Every `unreachable` names what was missing, so the distinct reasons
        # ARE the access worklist. Aggregated here rather than left implicit
        # because it is the one output somebody can act on without reading any
        # lead: it says which key to go and get, and what it unblocks.
        # Keyed on the blocker each probe ASSERTS, never on its prose. Grouping
        # on the detail string put one AccessDenied on three buckets into three
        # rows, which is the opposite of what a worklist is for.
        "access_worklist": access_worklist(leads),
        "not_checked": {
            # Before any count, because a lead whose access expires next week
            # is not a todo that can wait for the next sweep.
            "access_expiring_soon": [
                slim(l) | {"access_expires_at": l.get("access_expires_at"),
                           "days_left": expiry_state(l, a.expiring_soon_days)[1]}
                for l in leads
                if expiry_state(l, a.expiring_soon_days)[0] == "expiring_soon"],
            "access_expired_and_unresolved": [
                slim(l) | {"access_expires_at": l.get("access_expires_at"),
                           "why_it_matters": "access is gone and the lead was "
                                             "never resolved — this is the "
                                             "transition nothing else observes"}
                for l in leads
                if expiry_state(l, a.expiring_soon_days)[0] == "expired"
                and l["status"] in ("claim", "unreachable")],
            "unprobed_leads": [slim(l) for l in unprobed],
            "unreachable": [slim(l) for l in by["unreachable"]],
            "probe_older_than_days": a.recheck_days,
            "stale_probes": [slim(l) for l in stale],
        },
        # Not a finding about the world — a finding about this file. An untracked
        # record is one `git clean` or one fresh clone from never having existed,
        # and it is the one gap here that the sweep itself created.
        "record_unsaved": unsaved,
        # The two things a flat findings list cannot say: which cells of
        # searches.md's table were never looked in, and what is worth a second
        # look. Both before the findings, same reason the gaps are.
        "coverage": coverage(leads, usable_sources(project)),
        "anomalies": anomalies(leads),
        "exhaustive": False,
        "why_not_exhaustive":
            "a sweep finds what somebody wrote down or left a path to. Data that "
            "nobody documented and no surviving code points at will not appear "
            "here, and no number of clean probes changes that",
        "verified": [slim(l) for l in by["verified"]],
        "gone": [slim(l) for l in by["gone"]],
        "still_only_claimed": [slim(l) for l in by["claim"]],
        "counts": {k: len(v) for k, v in by.items()} | {"total": len(leads)},
        "measured": {
            "locations": len(measured),
            "bytes": sum(l["bytes"] for l in measured),
            "files": sum(l.get("files") or 0 for l in measured),
            # True whenever anything was not measured, which is almost always
            # during a handover. A total from a partial sweep is a floor.
            "is_lower_bound": len(measured) < len([l for l in leads
                                                   if l["status"] != "gone"]),
        },
        "next": ("/data-check to declare a layout contract for anything verified — "
                 "this skill deliberately does not, because unit_glob's depth is "
                 "load-bearing and a guess there is silent"),
    })


