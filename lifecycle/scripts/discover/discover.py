# anomalies — the part a person would otherwise have to notice
# --------------------------------------------------------------------------- #

def _sample_objects(lead):
    """-> [(basename, bytes)] parsed out of an s3 listing sample.

    Best-effort by design: a line this cannot parse is skipped rather than
    guessed at. A duplicate detector that invents a size is worse than none.
    """
    out = []
    for line in lead.get("probes", [{}])[-1].get("sample") or []:
        parts = str(line).split()
        if len(parts) < 4:
            continue
        try:
            size = int(parts[2])
        except (ValueError, IndexError):
            continue
        out.append((parts[-1].rsplit("/", 1)[-1], size))
    return out


def anomalies(leads):
    """-> the things worth a second look, computed rather than noticed.

    Everything here is mechanical. That is the point and also the limit: a script
    can say two objects share a name and a byte count, and cannot say whether that
    matters. So each entry carries what was observed and what it would mean, and
    the judgment stays with whoever reads it.

    The detectors, and why each one earned its place:

      status_flip          `verified` -> `gone` is data that disappeared between
                           two probes, which is the single most urgent thing this
                           tool can find. The reverse means an earlier probe was
                           wrong, and every conclusion drawn from it is suspect.
      duplicate_objects    same basename AND same byte count in two locations.
                           The Kontoor handover page says this out loud — the
                           fine-tune sets live in two prefixes and "sizes and
                           dates are the only way to tell copies apart" — which
                           is a job for a script, not a person.
      verified_but_empty   a location that answered and holds nothing. Not `gone`
                           (the path is there) and not a finding (nothing is in
                           it), so it falls between the statuses and would
                           otherwise read as a success.
      source_now_doubted   a source whose claims a probe has already contradicted.
                           One wrong path on a page does not make the page useless,
                           but it does change what the REST of it is worth, and
                           nothing else in the record carries that.
      claim_never_checked  a `claim` old enough that nobody is going to check it.
                           Recorded is not verified, and the gap widens silently.
    """
    out = []

    for l in leads:
        probes = l.get("probes") or []
        results = [p.get("result") for p in probes]
        for i in range(1, len(results)):
            before, after = results[i - 1], results[i]
            if before == "verified" and after == "gone":
                out.append({
                    "kind": "status_flip", "severity": "urgent",
                    "lead_id": l["lead_id"], "path": l["path"],
                    "observed": f"verified at {probes[i-1]['at']}, gone at "
                                f"{probes[i]['at']}",
                    "means": "this data existed when we looked and does not now. "
                             "Escalate while somebody still remembers — that is "
                             "/ask-human"})
            elif before == "gone" and after == "verified":
                out.append({
                    "kind": "status_flip", "severity": "watch",
                    "lead_id": l["lead_id"], "path": l["path"],
                    "observed": f"gone at {probes[i-1]['at']}, verified at "
                                f"{probes[i]['at']}",
                    "means": "an earlier probe said absent and was wrong. Anything "
                             "decided on that reading needs revisiting, and the "
                             "probe itself may be reporting absence too eagerly"})

        if l.get("status") == "verified" and (l.get("files") == 0
                                              or l.get("bytes") == 0):
            out.append({
                "kind": "verified_but_empty", "severity": "watch",
                "lead_id": l["lead_id"], "path": l["path"],
                "observed": "the location answered and holds 0 bytes / 0 files",
                "means": "not `gone` — the path is there — but nothing is in it. "
                         "Between the statuses, so it reads as a success unless "
                         "somebody says otherwise"})

    seen = {}
    for l in leads:
        if l.get("status") != "verified":
            continue
        for name, size in _sample_objects(l):
            seen.setdefault((name, size), []).append(l)
    for (name, size), where in seen.items():
        if len(where) < 2:
            continue
        out.append({
            "kind": "duplicate_objects", "severity": "watch",
            "lead_id": where[0]["lead_id"],
            "path": ", ".join(l["path"] for l in where),
            "observed": f"{name} appears in {len(where)} locations at exactly "
                        f"{size} bytes",
            "means": "the same bytes stored twice. Matters two ways: it inflates "
                     "any total, and deleting the wrong copy is not obviously a "
                     "deletion. Sizes and names are all a listing gives — a "
                     "checksum would settle it"})

    bad_sources = {}
    for l in leads:
        if l.get("status") == "gone" and l.get("evidence"):
            bad_sources.setdefault(l["evidence"], []).append(l)
    for evidence, wrong in bad_sources.items():
        same = [l for l in leads if l.get("evidence") == evidence]
        if len(same) < 2:
            continue
        out.append({
            "kind": "source_now_doubted", "severity": "watch",
            "lead_id": wrong[0]["lead_id"], "path": evidence,
            "observed": f"this source was wrong about {len(wrong)} of "
                        f"{len(same)} thing(s) it claimed",
            "means": "one wrong path does not make a source useless, but it "
                     "changes what the rest of it is worth. Re-probe its other "
                     "claims before relying on any of them"})

    for l in leads:
        if l.get("status") != "claim":
            continue
        age = age_days(l.get("recorded_at"))
        if age is not None and age >= 14:
            out.append({
                "kind": "claim_never_checked", "severity": "watch",
                "lead_id": l["lead_id"], "path": l["path"],
                "observed": f"recorded {age} days ago and never probed",
                "means": "recorded is not checked. A `claim` this old is one "
                         "nobody is going to get to on their own"})

    rank = {"urgent": 0, "watch": 1}
    out.sort(key=lambda a: (rank.get(a["severity"], 9), a["kind"]))
    return out


def usable_sources(project):
    """The usable-now source_type names, so `coverage` does not report a gap in a
    source nobody can reach. Reuses cmd_sources' logic by calling it rather than
    restating it — a second copy of "what is available" is a second copy that
    drifts, which is the argument that moved the sweep into one engine."""
    res, _rpath = workspace_resources(project)
    names = set()
    stages_dir = os.path.join(project, "stages")
    stages = sorted(os.listdir(stages_dir)) if os.path.isdir(stages_dir) else []
    for stage in stages:
        code = os.path.join(stages_dir, stage, "code")
        if os.path.isdir(code):
            names.add("code")
            if os.path.isdir(os.path.join(code, ".git")):
                names.add("git_history")
    for backend, spec in TRACKING.items():
        if spec["family"] == "disk" or credential_present(spec)[0]:
            names.add("tracking")
            break
    if res:
        _e, _w, registered = aws_env(res)
        if registered or os.environ.get("AWS_ACCESS_KEY_ID") or \
                os.path.isfile(os.path.expanduser("~/.aws/credentials")):
            names.add("s3")
        for key, srv in (res.get("servers") or {}).items():
            if not key.startswith("_") and (srv.get("host") or srv.get("alias")):
                names.add("server")
                break
    # A person is always available and a doc almost always is. Listing them as
    # "available but unswept" is correct and is the point: on a handover the wiki
    # and the people are exactly what does not get swept.
    names.update({"doc", "person"})
    return names


def lead_url(lead, res):
    """-> (url, derived) for a lead, or (None, False) when nothing can be built.

    **Derived at render time, never stored.** A console URL is a fact about
    somebody's web UI, not about the data, and baking one into `leads.json` means
    a record that goes wrong when a vendor reorganises their routes — while
    reading like part of the finding. The path is the record; a link is a
    convenience laid over it.

    `derived` is returned so the brief can mark it. A URL somebody typed in
    (`--url`) points where they meant; one this function built is a guess about a
    console that may 404, and those must not look alike to a reader deciding
    whether a lead is worth chasing.

    Only three derivations, and the restraint is deliberate: `s3`, `local` and
    `tracking:wandb` have unambiguous, stable public URL shapes. ClearML's web
    host is a different subdomain from its API host, MLflow's UI depends on how it
    is deployed, and a remote path over ssh has no URL a browser opens — guessing
    at those produces dead links, and a document whose links are half dead is one
    nobody clicks twice.
    """
    if lead.get("url"):
        return lead["url"], False
    on, path = lead.get("on") or "", lead.get("path") or ""

    if on == "s3" and path.startswith("s3://"):
        rest = path[len("s3://"):]
        bucket, _, key = rest.partition("/")
        if not bucket:
            return None, False
        # No region in the URL, deliberately. `resources.json -> aws.region` is one
        # global setting and a bucket has its own — the sweep that exercised this
        # had `us-west-2` configured and hit a bucket named `…-repo-ohio`, which is
        # us-east-2. Knowing a bucket's region takes an API call this render does
        # not make, so the regionless console route is used and AWS resolves it.
        # Asserting a region we guessed buys a slightly faster page load and risks
        # a link that lands on the wrong console.
        host = "s3.console.aws.amazon.com"
        qs = ""
        if key and not key.endswith("/"):
            # An object, not a prefix. The console needs a different route, and
            # sending an object to the prefix view lands on an empty listing —
            # which reads exactly like the data being gone.
            return f"https://{host}/s3/object/{bucket}?prefix={key}{qs}", True
        return f"https://{host}/s3/buckets/{bucket}?prefix={key}{qs}", True

    if on == "local":
        return "file://" + os.path.abspath(os.path.expanduser(path)), True

    if on == "tracking:wandb":
        loc = path.split(":", 1)[1] if path.lower().startswith("wandb:") else path
        loc = loc.strip("/")
        if loc and loc.count("/") <= 1:
            return f"https://wandb.ai/{loc}", True

    return None, False


def md_link(text, url):
    """A markdown link with the label kept as code, or bare code when there is no
    URL. `)` in a path would end the link early, so it is escaped."""
    if not url:
        return f"`{text}`"
    return f"[`{text}`]({url.replace(')', '%29')})"


