def cmd_record(a) -> None:
    project = os.path.expanduser(a.project)
    if not os.path.isdir(project):
        broke(f"project not found: {project}")
    rec = load_leads(project)

    on = a.on
    if on is None:
        on = "s3" if a.path.startswith("s3://") else "local"
    if not classify_on(on):
        broke(f"unknown --on {on!r}",
              allowed=list(ON_MACHINE_PROBEABLE) + list(ON_ASK_A_PERSON),
              why="validated here rather than at probe time so a value nothing "
                  "can dispatch never enters the record. An unknown `on` used to "
                  "fall through to the server probe and come back as a confident "
                  "`unreachable`, which reads as probed")

    dup = next((l for l in rec["leads"] if l["path"] == a.path and l["on"] == on), None)
    if dup and not a.again:
        refuse(f"already recorded as {dup['lead_id']} ({dup['status']})",
               lead=dup,
               why="two leads for the same path would each be probed and each be "
                   "reported, which turns one place into two findings",
               fix="--again to add a second lead anyway (different claim about "
                   "the same path), or edit the record")

    lead = make_lead(
        rec, path=a.path, on=on, source_type=a.source_type, subject=a.subject,
        evidence=a.evidence, what=a.what, url=a.url, evidence_url=a.evidence_url,
        dataset=a.dataset, note=a.note, access_expires_at=a.access_expires_at)
    rec["leads"].append(lead)
    rec["updated_at"] = now_utc()
    atomic_write_json(leads_path(project), rec)
    emit({"recorded": lead["lead_id"], "lead": lead,
          "path": leads_path(project),
          "next": "probe it — a claim is not a finding"})


def make_lead(rec, *, path, on, source_type, subject, evidence, what,
              url=None, evidence_url=None, dataset=None, note=None,
              access_expires_at=None):
    """The one place a lead's shape is written.

    Two callers build leads — `record` from a person's argv and `introspect` from
    a checkpoint's own metadata — and a second literal would drift. Everything a
    later reader needs to tell one source of a lead from another is already on the
    lead (`source_type`, `evidence`), so the two paths must produce the same shape
    and differ only in those values.
    """
    return {
        "lead_id": f"lead_{len(rec['leads']) + 1:04d}",
        "path": path,
        "on": on,
        "source_type": source_type,
        # Which of the four searches this lead belongs to. `unclassified` is
        # allowed and is reported as a gap rather than guessed at: inferring the
        # subject from a path would make the coverage table confidently wrong.
        "subject": subject,
        # Two URLs on two axes, same split as `on` versus `source_type`: where the
        # THING is, and where the CLAIM came from. One link cannot be both, and a
        # brief that conflated them would send a reader to a wiki page when they
        # asked to see the bucket.
        "url": url,
        "evidence_url": evidence_url,
        # Not optional. A lead with no evidence is a rumour, and six months on
        # nobody can tell which of these came from a config file that ran and
        # which came from a wiki page somebody wrote from memory.
        "evidence": evidence,
        "what": what,
        "status": "claim",
        "recorded_at": now_utc(),
        "probes": [],
        "dataset": dataset,
        "note": note,
        # None means "no known deadline", which is the normal case. A date here
        # says this lead stops being resolvable then — see DEFAULT_EXPIRING_SOON_DAYS.
        "access_expires_at": access_expires_at,
        # What the path's own SHAPE implies — see PATH_SHAPES. Computed at record
        # time and stored, because it is derived from the string and the string is
        # what a later reader has. Never a status: it redirects the fix and names
        # leads worth opening, and a probe always outranks it.
        "path_shape": path_shape(path),
    }


def _dispatch_probe(lead, resources, budget_seconds):
    """-> (status, detail, sample, size). Which probe function to run, keyed by
    `lead["on"]`'s kind -- or a fallback status for the three cases nothing
    can be dispatched for: no machine attached, a person has to answer, or an
    `on` value this code does not recognize."""
    on = lead["on"]
    kind = classify_on(on)
    if on == "local":
        return probe_local(lead["path"], budget_seconds)
    if on == "s3":
        return probe_s3(lead["path"], resources, budget_seconds)
    if on.startswith("tracking:"):
        return probe_tracking(on, lead["path"], budget_seconds)
    if on.startswith("server:"):
        return probe_server(on.split(":", 1)[1], lead["path"], resources, budget_seconds)
    if kind == "no_probe":
        # A path with no machine attached. Distinct from `ask` (somebody can
        # answer it) and from a bad `on` (a typo): this IS the right value,
        # and what is missing is the host. So the blocker names the actual
        # task — identify the machine — and lands it on the access worklist,
        # where a credential ask would not have helped.
        # The shape of the path changes what the fix IS. `/workspace/...` is a
        # container path: naming the host does not resolve it, because the host
        # filesystem has no such path. Sending somebody to ssh in and `ls` sends
        # them to look where the path was never at, and they come back with a
        # `gone` that means nothing.
        shape = lead.get("path_shape") or path_shape(lead.get("path"))
        base = (f"the path is recorded but no machine is: `on: {on}`. Nothing "
                f"can be dispatched until somebody says which host this path "
                f"was on. That identification is the access task, not a key")
        extra = {"blocker": "host_unidentified"}
        if shape:
            base = (f"the path is recorded but no machine is: `on: {on}` -- and "
                    f"the path's own shape says naming one would not be enough. "
                    f"{shape['why']}. What resolves it: {shape['resolved_by']}")
            extra = {"blocker": f"{shape['environment']}_path_not_host_path",
                     "path_shape": shape}
            if shape.get("derived_lead"):
                extra["open_this_instead"] = shape["derived_lead"]
        return ("unreachable", base, None, extra)
    if kind == "ask":
        # Leave the status alone. Overwriting `claim` with `unreachable` here
        # would say "we could not look" about something a person can simply
        # answer, and would move the lead out of the set /ask-human works on.
        return (lead["status"],
                f"`{on}` is not machine-probeable — somebody has to answer it. "
                f"/ask-human, and their answer is a claim until a probe agrees",
                None, {})
    # Unreachable in the most literal sense: this code cannot reach it,
    # and saying so is better than guessing a probe.
    return ("unreachable", f"unknown `on` value {on!r}; no probe dispatched",
            None, {})


def cmd_probe(a) -> None:
    project = os.path.expanduser(a.project)
    rec = read_json(leads_path(project), required=False)
    if rec is None:
        refuse("no leads recorded yet", fix="discover.py record")
    resources, _ = workspace_resources(project)

    todo = [l for l in rec["leads"]
            if (a.id is None or l["lead_id"] == a.id)
            and (a.all or not l["probes"]
                 or (age_days(l["probes"][-1]["at"]) or 1e9) >= a.recheck_days)]
    if a.id and not todo:
        known = [l["lead_id"] for l in rec["leads"]]
        if a.id not in known:
            broke(f"no lead {a.id!r}", known=known)
        todo = [l for l in rec["leads"] if l["lead_id"] == a.id]
    if not todo:
        return emit({"probed": [], "note": "every lead has a probe newer than "
                                           f"{a.recheck_days} days — --all to redo them"})

    probed = []
    for lead in todo:
        on = lead["on"]
        status, detail, sample, size = _dispatch_probe(lead, resources, a.budget_seconds)
        lead["probes"].append({"at": now_utc(), "result": status, "detail": detail,
                               "sample": sample, **size})
        lead["status"] = status
        # Carried onto the lead so the table can be drawn without re-walking
        # anything. `null` means not measured; it never means zero.
        lead["bytes"] = size.get("bytes")
        lead["files"] = size.get("files")
        lead["size_not_measured"] = size.get("not_measured")
        probed.append({"lead_id": lead["lead_id"], "path": lead["path"],
                        # The sample IS the payload for some probes — a tracking
                        # entity's project names are the answer, not a garnish —
                        # so emit it rather than only persisting it.
                        "sample": sample,
                        "on": on, "status": status, "detail": detail,
                        "bytes": size.get("bytes"), "files": size.get("files"),
                        "size_not_measured": size.get("not_measured"),
                        "was_claimed": lead.get("what"),
                        "evidence": lead.get("evidence")})

    rec["updated_at"] = now_utc()
    atomic_write_json(leads_path(project), rec)

    gone = [r for r in probed if r["status"] == "gone"]
    unreachable = [r for r in probed if r["status"] == "unreachable"]
    emit({
        "probed": probed,
        "counts": {k: sum(1 for r in probed if r["status"] == k) for k in STATUSES},
        # The handover finding, on its own line. A claim that probed to `gone`
        # is the one worth acting on today, while somebody might still remember.
        "gone": [{"path": r["path"], "claimed": r["was_claimed"],
                  "evidence_said": r["evidence"]} for r in gone],
        "could_not_look": [{"path": r["path"], "why": r["detail"]} for r in unreachable],
        "note": None if not unreachable else
                f"{len(unreachable)} lead(s) could not be looked at. They are "
                f"UNREACHABLE, not empty — re-probe when access arrives.",
    })
    if gone:
        sys.exit(1)


