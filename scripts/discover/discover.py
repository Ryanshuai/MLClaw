def cmd_sources(a) -> None:
    """What is available to sweep, and which of those are usable right now.

    This verb exists so that "what did you not check" has an answer. Without a
    list of what COULD have been checked, a findings list is unfalsifiable: it
    looks complete no matter how little was looked at.

    It used to list only what `resources.json` registered, which made it wrong in
    the one direction that matters: with nothing registered it reported a single
    blocked source, so a project whose git history and on-disk tracking leftovers
    were sitting there unread looked like a project with nothing to read. Those are
    the CREDENTIAL-FREE sources — the only ones available in the weeks a handover
    actually starts in — and omitting them turned this verb into an argument for
    waiting. Every family `searches.md` ranks now has a row.

    Two distinctions the rows carry, because collapsing either one sends the reader
    to the wrong place:

      `kind`        mine (a place to find candidate locations) vs probe (a location
                    kind something can go and classify) vs ask (a person)
      `blocked_by`  credential (a key away) vs human (no key will ever help) vs
                    registration vs absent. "Blocked" alone routes a wiki page to
                    the same queue as an expired AWS key.
    """
    project = os.path.expanduser(a.project)
    if not os.path.isdir(project):
        broke(f"project not found: {project}")
    resources, rpath = workspace_resources(project)

    rows = []

    def add(source, kind, usable, why=None, blocked_by=None, fix=None, **extra):
        row = {"source": source, "kind": kind, "usable": bool(usable),
               "why": why, "blocked_by": None if usable else blocked_by,
               "fix": fix}
        row.update(extra)
        rows.append(row)

    stages_dir = os.path.join(project, "stages")
    stages = sorted(os.listdir(stages_dir)) if os.path.isdir(stages_dir) else []
    code_dirs = []
    for stage in stages:
        code = os.path.join(stages_dir, stage, "code")
        if os.path.isdir(code):
            code_dirs.append((stage, code))

    # --- credential-free, and therefore first. searches.md's ranking, in order.

    # checkpoint — the tracking backend that ships inside the weights. First,
    # because it needs less than anything else here (one local file, no host, no
    # key) and because what it names was written by the training process rather
    # than asserted by a person. Always `usable`: unlike every other row this one
    # is not contingent on the project's state, only on the caller having a file.
    ckpts = local_checkpoints(project, resources)
    add("checkpoint", "mine", True,
        why="`introspect` a .pt and read what the run itself recorded: the val "
            "split it measured on (train_args.data), the checkpoint it was "
            "fine-tuned from (train_args.model), its own metrics, its params, and "
            "whether a commit was ever stamped. Needs no credential and no host — "
            "pass any checkpoint already on this disk, or pull one first",
        found_on_disk=ckpts[:10] or None,
        found_on_disk_count=len(ckpts))

    # code — a path a script read is a path that existed.
    for stage, code in code_dirs:
        add(f"code:{stage}", "mine", True, root=code,
            why="grep for data roots, dataset classes, config YAMLs, "
                "`--data-dir` defaults, docker mounts, .env files")
    if not code_dirs:
        add("code", "mine", False, blocked_by="absent",
            why="no stage has a code/ directory yet — nothing to grep",
            fix="/train-init or /eval-init")

    # git history — the only source that shows what MOVED, and free.
    for stage, code in code_dirs:
        is_git = os.path.isdir(os.path.join(code, ".git"))
        add(f"git_history:{stage}", "mine", is_git, root=code,
            why="`git log -S<path>`, `--diff-filter=D`, deleted configs, and "
                "commit messages — which carry intent no config does"
            if is_git else "the code snapshot is not a git tree, so removed "
                           "paths and commit messages are unavailable",
            blocked_by="absent")

    # tracking, disk family — no import, no network, no key. The one tracking
    # history readable on day one, which is why it outranks every service backend.
    disk = sorted(k for k, s in TRACKING.items() if s["family"] == "disk")
    somewhere = bool(code_dirs) or bool((resources or {}).get("local", {}).get("base_paths"))
    add("tracking_disk", "probe", somewhere,
        backends=disk,
        why=f"glob for {', '.join(sorted({m for k in disk for m in TRACKING[k]['markers']}))}"
        if somewhere else "no code directory and no local base path to glob under",
        blocked_by="absent")

    # tracking, service family — one row each, because "which backends can I list
    # right now" is the question a takeover asks and a single row cannot answer.
    for backend in sorted(k for k, s in TRACKING.items() if s["family"] == "service"):
        spec = TRACKING[backend]
        have, where = credential_present(spec)
        add(f"tracking:{backend}", "probe", have,
            why=(f"credential from {where}" if have else where),
            blocked_by="credential", fix=None if have else "/resources or the key owner",
            listing=("rest" if spec.get("listing") in REST_LISTINGS
                     else spec.get("listing")))

    # --- registered, and therefore contingent on somebody having registered it.

    if resources is None:
        add("resources.json", "probe", False, blocked_by="registration",
            why=f"not found at {rpath} — no server, S3 or vendor is registered "
                f"yet, so none of them can be swept", fix="/resources")
    else:
        # Report the credential the PROBE will use, not merely that one exists
        # somewhere. These two answers used to be computed differently — this row
        # read `resources.json` while `probe_s3` inherited whatever the CLI
        # resolved — so the checklist could call s3 usable on the strength of a key
        # nothing then used, and the sweep reported no access over readable data.
        aws = resources.get("aws") or {}
        _env, where, registered = aws_env(resources)
        has_aws = bool(registered or os.environ.get("AWS_ACCESS_KEY_ID")
                       or os.path.isfile(os.path.expanduser("~/.aws/credentials")))
        # The declared bucket is a run's default, NOT the sweepable surface, and
        # this row used to report it as `bucket` with nothing to contradict the
        # reading. A credential routinely reaches many more; scoping a sweep to the
        # declared one and calling the result a sweep is how twenty buckets became
        # three. The reach is a network question, so it is `surface`'s, and this row
        # reports what the last dated reading found or says nothing was ever read.
        surf = (load_surface(project) or {}).get("s3") or {}
        reach = sorted(surf.get("buckets") or {})
        surf_age = age_days(surf.get("measured_at")
                            or (load_surface(project) or {}).get("measured_at"))
        s3_extra = {
            "declared_bucket": aws.get("s3_bucket") or None,
            "reachable_buckets": reach or None,
            "reachable_count": len(reach) if reach else None,
            "surface_measured_days_ago": surf_age,
            "surface_by_state": surf.get("by_state") or None,
        }
        if not reach:
            s3_extra["surface_warning"] = (
                "the credential's reach has NEVER been enumerated — the declared "
                "bucket is a run's default, not the surface. A sweep scoped to it "
                "may be covering a fraction of what is readable. Run "
                "`discover.py surface` (network)")
        elif surf.get("enumerated") is False:
            s3_extra["surface_warning"] = (
                "bucket enumeration failed at the last reading, so this list is a "
                "LOWER BOUND on the reach, not the reach")
        add("s3", "probe", has_aws, credential=where,
            why=(f"probes will use {where}" if has_aws else
                 "no AWS credentials — every s3:// lead stays UNREACHABLE, which "
                 "is not the same as empty"),
            blocked_by="credential", fix=None if has_aws else "/resources",
            **s3_extra)
        for key, srv in (resources.get("servers") or {}).items():
            if key.startswith("_"):
                continue
            ok = bool(srv.get("host") or srv.get("alias"))
            add(f"server:{key}", "probe", ok,
                root=srv.get("mlclaw_root") or None,
                why=None if ok else "no host or alias recorded",
                blocked_by="registration", fix=None if ok else "/resources")
        for p in (resources.get("local") or {}).get("base_paths") or []:
            there = os.path.isdir(os.path.expanduser(p))
            add("local", "probe", there, root=p,
                why=None if there else "the base path is not on this machine",
                blocked_by="absent")
        for key, _party in (resources.get("outsourcing") or {}).items():
            if key.startswith("_"):
                continue
            # A vendor can be holding the only copy of a batch. They are a source
            # of ANSWERS, not of listings — hence /ask-human, not a probe.
            add(f"outsourcing:{key}", "ask", False, blocked_by="human",
                why="a party MLClaw cannot list; ask them", fix="/ask-human")

    # --- never machine-swept, and that is a property of the source, not a gap.
    #
    # Listed anyway: "did anybody read the handover page" is a real question, and a
    # verb that omits the sources it cannot automate reports a complete sweep of
    # the half of the world it can reach.
    add("doc", "ask", False, blocked_by="human",
        why="no doc probe exists; query by project/repo/dataset name and record "
            "what you find as `claim`. Uniquely good for two things no listing "
            "has: WHY a thing exists, and numbers nobody logged",
        fix="/ask-human, and --access-expires-at if the page itself is at risk")
    add("person", "ask", False, blocked_by="human",
        why="the last resort and often the only one; their answer is a `claim` "
            "until something else agrees", fix="/ask-human")

    usable = [s for s in rows if s["usable"]]
    tally = {}
    for s in rows:
        if not s["usable"]:
            tally[s["blocked_by"] or "unstated"] = tally.get(s["blocked_by"] or "unstated", 0) + 1
    notes = []
    access = tally.get("credential", 0) + tally.get("registration", 0)
    if access:
        notes.append(f"{access} source(s) cannot be swept until access or "
                     f"registration arrives. Anything they hold will be recorded "
                     f"UNREACHABLE, never `gone`.")
    if tally.get("human"):
        notes.append(f"{tally['human']} source(s) are never machine-swept (docs, "
                     f"people, vendors). What they yield stays `claim` — no "
                     f"credential changes that.")
    free = [s["source"] for s in usable if s["kind"] == "mine"
            or s["source"] == "tracking_disk"]
    if free:
        notes.append(f"Sweepable right now with no credential at all: "
                     f"{', '.join(free)}. Start here.")
    emit({
        "project": project,
        "sources": rows,
        "counts": {"total": len(rows), "usable_now": len(usable),
                   "blocked": len(rows) - len(usable)},
        "blocked_by": tally,
        # Said plainly, because on a handover this number is large and shrinking,
        # and a sweep run today is a sweep of a fraction of the world.
        "note": " ".join(notes) or None,
    })


# --------------------------------------------------------------------------- #
# introspect — the checkpoint is a source, not just a file with a size
# --------------------------------------------------------------------------- #
#
# `searches.md` ranks tracking backends with the line "a run that trained recorded
# what it read". A modern checkpoint does exactly that, offline, inside the
# artifact — and the family was missing, so every sweep treated a `.pt` as a name
# and a byte count. What that costs is specific and it lands on evaluation: eval's
# two needs are a checkpoint and a val set, the checkpoint is usually the easiest
# thing in the world to obtain (it is the deployed artifact), and it NAMES THE VAL
# SET. Not opening it means the one search with the highest yield for the one
# stage that most needs it was never run.


class _Stub:
    """Stand-in for a class this interpreter does not have.

    Reading a checkpoint's metadata must not require the framework that wrote it —
    that would put torch in the dependency path of a record-keeping script and
    make the answer "the package is not installed" instead of a finding. So every
    global the pickle names becomes an inert type. NOTHING FROM THE FILE IS
    EXECUTED: `find_class` fabricates a type, it never imports one, and
    `__reduce__` keeps re-pickling harmless.
    """

    _mod = _name = "?"

    def __init__(self, *a, **kw):
        self._args = a

    def __repr__(self):
        return f"<{self._mod}.{self._name}>"

    def __setstate__(self, state):
        self._state = state

    def append(self, *a):
        pass

    def __setitem__(self, *a):
        pass

    def __reduce__(self):
        return (object, ())


_STUBS = {}


def _stub_for(mod, name):
    """A CLASS, not a factory — pickle's NEWOBJ opcode requires a type."""
    key = (mod, name)
    if key not in _STUBS:
        _STUBS[key] = type(name, (_Stub,), {"_mod": mod, "_name": name})
    return _STUBS[key]


def read_torch_metadata(path):
    """-> (dict, None) | (None, why). The top-level dict of a torch .pt.

    A torch>=1.6 checkpoint is a zip holding one pickle. Only the top level is
    wanted: the tensors stay as placeholders because `persistent_load` refuses to
    resolve storages, so this reads a 63 MB file without materialising a weight.
    """
    import io
    import pickle
    import zipfile

    try:
        z = zipfile.ZipFile(path)
    except Exception as exc:                        # not a zip -> not this shape
        return None, f"not a zip archive ({type(exc).__name__})"
    pkls = [n for n in z.namelist() if n.endswith("data.pkl")]
    if not pkls:
        return None, ("a zip, but no */data.pkl member — not a torch checkpoint "
                      "(safetensors and plain-pickle .pth are different shapes "
                      "and have no reader here)")

    class Safe(pickle.Unpickler):
        def find_class(self, mod, name):
            if mod == "collections" and name == "OrderedDict":
                return dict
            return _stub_for(mod, name)

        def persistent_load(self, pid):
            return _Stub()

    try:
        top = Safe(io.BytesIO(z.read(pkls[0]))).load()
    except Exception as exc:
        return None, f"the pickle did not load: {type(exc).__name__}: {exc}"
    if not isinstance(top, dict):
        return None, (f"the checkpoint's top level is {type(top).__name__}, not a "
                      f"dict — a bare state_dict records nothing about its training")
    return top, None


def plain(v):
    """JSON-safe or dropped. A stub rendered as a string would look like data."""
    if isinstance(v, (str, int, float, bool, type(None))):
        return v
    if isinstance(v, (list, tuple)):
        cleaned = [plain(x) for x in v]
        return None if any(x is None and y is not None
                           for x, y in zip(cleaned, v)) else cleaned
    if isinstance(v, dict):
        return {str(k): plain(x) for k, x in v.items()
                if isinstance(x, (str, int, float, bool, type(None), list, dict))}
    return None


def leads_from_ultralytics(top, ckpt_path):
    """-> [proposed lead dicts]. What this checkpoint says about the world.

    Deliberately narrow: only fields whose meaning is unambiguous become leads.
    `train_args.data` and `train_args.model` are paths the training process
    actually opened, which is the strongest kind of evidence a sweep ever gets —
    stronger than a wiki page and stronger than a grep, because the run would
    have crashed if they had been wrong.

    `train_metrics` becomes a `results` lead rather than a number written
    anywhere authoritative, and it is recorded as a CLAIM even though it was read
    out of an artifact. That is not timidity: the metric has no `scope` — nothing
    in the checkpoint says which images it was measured on — and per CLAUDE.md a
    metric without a scope cannot be compared to anything. A `verified` here
    would be a number that reads as checked and cannot be used.
    """
    ta = top.get("train_args") or {}
    if not isinstance(ta, dict):
        ta = {}
    leads = []
    ck = os.path.basename(ckpt_path)

    data_path = ta.get("data")
    if isinstance(data_path, str) and data_path:
        leads.append({
            "path": data_path, "subject": "data", "on": ON_HOST_UNKNOWN,
            "what": "THE VAL SPLIT — this file declares which units are train and "
                    "which are val, so it is the only definition of the quantity "
                    "this checkpoint's recorded metrics refer to. Without it a "
                    "re-measurement is a different measurement, not a reproduction",
            "evidence": f"train_args.data, read out of {ck}",
        })
    parent = ta.get("model")
    if isinstance(parent, str) and parent and parent.endswith((".pt", ".pth")):
        leads.append({
            "path": parent, "subject": "weights", "on": ON_HOST_UNKNOWN,
            "what": "the checkpoint this one was fine-tuned FROM — one edge of the "
                    "lineage chain, recorded by the training process rather than "
                    "by a person",
            "evidence": f"train_args.model, read out of {ck}",
        })
    metrics = plain(top.get("train_metrics")) or {}
    if metrics:
        leads.append({
            "path": ckpt_path, "subject": "results", "on": "local",
            "what": "metrics this checkpoint records about ITSELF: "
                    + ", ".join(f"{k}={v}" for k, v in sorted(metrics.items())[:6])
                    + ". NO SCOPE IS RECORDED — nothing here says which units these "
                      "were measured on, so they are uncomparable until the val "
                      "split above is found. A claim, from an artifact",
            "evidence": f"train_metrics, read out of {ck}",
        })
    return leads


def local_checkpoints(project, resources, cap=200):
    """-> [paths] of checkpoint-shaped files already on this disk.

    A convenience for `sources`, not a search: it looks in the project and in the
    registered local base paths so the row can say "here are three you could read
    right now" instead of "go find one". Bounded and silent on error — a listing
    that cannot be taken must not make the row look unusable, because the row's
    real claim is "this needs nothing", which stays true with zero files found.
    """
    roots = [project]
    for base in ((resources or {}).get("local") or {}).get("base_paths") or []:
        p = os.path.expanduser(base if isinstance(base, str) else base.get("path", ""))
        if p and os.path.isdir(p):
            roots.append(p)
    hits = []
    for root in roots:
        _checkpoint_paths_under(root, hits, cap)
        if len(hits) >= cap:
            return sorted(hits)
    return sorted(hits)


def _checkpoint_paths_under(root, hits, cap):
    """Walk one root, appending checkpoint-shaped file paths to `hits` in
    place, stopping the moment `cap` is reached."""
    for dirpath, dirs, names in os.walk(root, onerror=lambda e: None):
        dirs[:] = [d for d in dirs if not d.startswith((".git", "__pycache__"))]
        for n in names:
            if n.endswith((".pt", ".pth", ".ckpt", ".safetensors")):
                hits.append(os.path.join(dirpath, n))
                if len(hits) >= cap:
                    return


def cmd_introspect(a) -> None:
    """Read a checkpoint and report the leads it names.

    A MINE, not a probe — the same `kind` as `code` and `git_history` in
    `sources`: it produces candidate locations rather than classifying one. So it
    looks by default and writes only with `--record`, matching CLAUDE.md's
    "confirm before saving".

    Exit 1 when there is no reader for the shape. That is the script working: an
    unreadable checkpoint must not fall back to a hand-guess about what trained,
    because the whole value here is that the training process wrote these fields
    and a person did not.
    """
    project = os.path.expanduser(a.project)
    if not os.path.isdir(project):
        broke(f"project not found: {project}")
    if not os.path.exists(a.checkpoint):
        broke(f"no such file: {a.checkpoint}")

    top, why = read_torch_metadata(a.checkpoint)
    if top is None:
        refuse("no reader for this checkpoint shape", why=why,
               checkpoint=a.checkpoint,
               readers_built=["torch/ultralytics .pt (zip + */data.pkl)"],
               readers_missing=["safetensors", "plain-pickle .pth",
                                "ONNX metadata_props", "TF SavedModel"],
               fix="`gone` is not the verdict here and neither is a guess: the "
                   "file is present and this code cannot read it. Name the shape "
                   "and add a reader")

    proposed = leads_from_ultralytics(top, a.checkpoint)
    found = {
        "reader": "torch/ultralytics .pt",
        "recorded_by_the_training_process": {
            "saved_at": plain(top.get("date")),
            "framework_version": plain(top.get("version")),
            "epochs_in_curve": len((top.get("train_results") or {}).get("epoch")
                                   or []) or None,
            "resumable": None if top.get("epoch") is None
                         else top.get("epoch") != -1,
        },
        # The code axis, straight from the horse's mouth. A null commit here is
        # not "we did not look" — the writer looked and found nothing, which is
        # the difference /repro's axes.md turns on.
        "code_axis": plain(top.get("git")),
        "params": plain(top.get("train_args")),
        "metrics": plain(top.get("train_metrics")),
        "leads_named": proposed,
    }
    if not a.record:
        found["note"] = (f"{len(proposed)} lead(s) named and NONE recorded — "
                         f"--record to write them")
        return emit(found)

    rec = load_leads(project)
    written = []
    for p in proposed:
        lead = make_lead(rec, path=p["path"], on=p["on"],
                         source_type="checkpoint", subject=p["subject"],
                         what=p["what"], evidence=p["evidence"],
                         dataset=a.dataset)
        rec["leads"].append(lead)
        written.append(lead["lead_id"])
    rec["updated_at"] = now_utc()
    atomic_write_json(leads_path(project), rec)
    found["recorded"] = written
    found["note"] = (f"{len(written)} lead(s) recorded as `claim`. Every path a "
                     f"checkpoint names is on a host nothing records, so they are "
                     f"`on: {ON_HOST_UNKNOWN}` — identify the machine before "
                     f"probing, and that identification is an access task")
    emit(found)


